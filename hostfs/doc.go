// Package hostfs は、檻が書いたファイル (敵対入力) を、ホストが安全に読むための、最小の関数を提供する。
//
// 読むのは、os.Root の中の通常のファイルだけで、大きさの上限を必ず指定する。標準ライブラリだけで書き、os/exec を使わない。
// 保証しない: ファイルの中身の正しさ (読んだ後に、どう解釈するかは、呼び出し側の責任)。
//
// # 使い方
//
//	root, err := os.OpenRoot(dir)
//	data, err := hostfs.ReadFile(root, "out.bundle", 1<<20)
//
// # 規則
//
//   - confine: 名前は root の中の相対 path だけ。root の外へ出る名前は、os.Root が拒否する。
//   - regular: 名前の途中と最後が symlink、または最後が FIFO・ソケット・デバイス・ディレクトリなら、開かずに拒否する。
//   - pin: 開いた fd と名前の Lstat が、同じ通常のファイルでなければ拒否する (開く間の差し替え)。O_NONBLOCK で開く。
//   - limit: 大きさが上限を超えるファイルは拒否する。読む間に伸びた分も、上限までしか読まない。
//
// # 限界
//
//   - 開いた後の中身の変化 (別のプロセスが書き続ける) は、読む長さの上限でしか抑えない。ハードリンク (Nlink) は見ない (読むだけ)。
//   - os.Root は、bind mount・/proc・デバイスファイルを禁止しない。root の中の mount は、検出できない。
