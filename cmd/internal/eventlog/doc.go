// Package eventlog は、chat の耐久イベントログ (ADR 0023・0026・0027・0053) の、同期の Store である。
//
// セッションごとの SQLite (modernc.org/sqlite。ADR 0026 の例外で、この package だけが import してよい) に、
// 進行中の起動の durable な Event の JSON を残す。
//
// この package は、素朴で同期的である。非同期の書き手・書き込み済みの最大の seq (W)・縮退の判定・Hub との境目は、chat 側 (ADR 0053)。
// chat を import しない (型は基本型だけ: seq・JSON のバイト列)。
//
// 守っていること:
//   - ファイルは、セッションのディレクトリ (自分のもの・他の人に書けない) の中に、os.Root で、0600・symlink を辿らずに作る。
//     DB は、先に O_EXCL で作ってから SQLite に渡す (-wal・-shm は、DB と同じ 0600 になる)。開いたあとにも、種類・uid・権限・
//     同じファイルであること、を確かめる。
//   - 掃除用のロックは、セッションのディレクトリ自身の fd への flock (lock ファイルは無い。rename・差し替えで外せない)。Open は、ロックを取ってから DB を作る。
//     SweepStale は、ロックが取れたものだけを消す (生きている DB のロックは取れない)。serve の lockDir とは無関係。
//   - Trim の返り値 (hello の first_seq の元) は、「削った範囲より後の、固定でない行の最小の seq (無ければ 0)」で、固定でない行の最小を
//     単純に返すのではない。0 でない返り値は単調に増える (何も消さない Trim が、前より低い値を返さない。固定が解けても戻らない)。
//   - SQL は固定の文で、値は全てバインド変数。DSN の path は、URI のエスケープをする (?・#・% を含む path でも切れない)。
//   - DB の中身は信用しない: 別のプロセスが書き換えた DB を読んでも、panic しない・無限に読まない。1 行の大きさ・1 回の読み取りの
//     件数とバイトに上限がある。呼び手は、Range の Payload を、配る前に検証する (JSON として妥当か・大きさ)。
//   - 一時ファイルに、中身を書かない (temp_store=MEMORY)。
//
// 限界: SQLite は、path で DB を開く。ディレクトリが、Open の途中で入れ替えられる (同じ利用者の別のプロセス) 場合は、開いたあとの
// 検査 (path が、作ったファイルと同じ) で検出するが、検出までの間は防げない。ディレクトリが他の人に書けないことは、Open が確かめる。
